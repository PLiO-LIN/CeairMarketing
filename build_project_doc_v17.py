def add_module(doc, title, paragraphs, focus_rows=None, focus_note=None):
    """A deliberately dense one-page analysis module for the V1.7 appendices."""
    doc.add_page_break()
    base.add_heading(doc, title, 2)
    for paragraph in paragraphs:
        base.add_text(doc, paragraph, size=11.2, after=2, line=1.32)
    if focus_rows:
        base.add_table(doc, focus_rows, [1800, 3900, 3300], font_size=9.2)
    if focus_note:
        p = base.add_label_text(doc, "审查结论：", focus_note, after=0)
        p.paragraph_format.line_spacing = 1.28


